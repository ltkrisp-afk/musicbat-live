 let calls=0,writes=0,processorCalls=0;
 globalThis.acceptanceState={env:{MUSICBAT_BASE_URL:origin,MUSICBAT_STRIPE_MODE:'test',STRIPE_SECRET_KEY:'sk_test_fixture',MUSICBAT_ACCEPTANCE_OWNER_ID:'owner',DB:{prepare(){calls++;return {bind(){return {first:async()=>({id:1,audio_url:'fixture'}),all:async()=>({results:[]})};}};},batch:async()=>writes++},BUCKET:{get:async()=>object},...env},user,isStripeSandboxKey:key=>/^sk_test_/.test(key??''),stripeGet:async(_env,path)=>{calls++;processorCalls++;return path==='/v1/account'?{id:'acct_1UHA0OLKJHBmA7Jw'}:{id:'acct_1UQrXtLKJHXYfqXB',metadata:{musicbat_artist_id:'local_seedy'},charges_enabled:true,payouts_enabled:true,details_submitted:true};},runCheckoutRecovery:async()=>{writes++;return {ran:true};}};
