test('sandbox operations reject anonymous visitors, other users, production and disabled configuration before any dependency calls',async()=>{
 for(const options of [{user:null},{user:{userId:'other'}},{url:'https://musicbat.audio'},{env:{MUSICBAT_BASE_URL:'https://musicbat.audio'}},{env:{MUSICBAT_STRIPE_MODE:'live'}},{env:{STRIPE_SECRET_KEY:'sk_live_fixture'}},{env:{MUSICBAT_ACCEPTANCE_OWNER_ID:undefined}}])assert.deepEqual(await run(options),{status:404,calls:0,writes:0});
});
test('cross-origin submissions cannot mutate fixtures or run recovery',async()=>{
 assert.deepEqual(await run({requestOrigin:'https://evil.invalid',operation:'recover'}),{status:403,calls:0,writes:0});
});
